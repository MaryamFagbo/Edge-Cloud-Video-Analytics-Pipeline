import numpy as np
import matplotlib.pyplot as plt

def run_distributed_vision_pipeline():
    # Ensure reproducible stochastic telemetry streams
    np.random.seed(1337)
    total_frames = 75

    # Simulate dynamic networking and device telemetry
    # Network throughput (Mbps) modeled with skewed volatility
    network_bandwidths = np.random.gamma(shape=4.0, scale=3.5, size=total_frames) + 1.5
    # Local processor workload utilization percentage
    processor_loads = np.clip(np.random.normal(70.0, 12.0, total_frames), 15.0, 100.0)

    execution_strategies = []  # 0: Local Edge Processing, 1: Split-Layer Offloading, 2: Full Cloud Migration
    end_to_end_latencies = []
    network_payloads = []

    for t in range(total_frames):
        bw = network_bandwidths[t]
        load = processor_loads[t]

        # Adaptive offloading logic based on real-time resource contention
        if load > 90.0 or bw < 3.0:
            # High hardware contention or severe network bottleneck -> Keep processing local
            strategy = 0
            latency = 18.0 + (load * 0.08)
            payload = 0.0  # Zero network utilization
        elif 3.0 <= bw < 18.0:
            # Moderate bandwidth -> Offload intermediate tensor layers (Split Computing)
            strategy = 1
            latency = 9.0 + (18.0 / bw) + (load * 0.03)
            payload = 1.8  # Megabits per intermediate tensor block
        else:
            # Ample network capacity and manageable edge load -> Offload complete frame payload
            strategy = 2
            latency = 5.0 + (30.0 / bw)
            payload = 10.5  # Megabits for uncompressed frame data

        execution_strategies.append(strategy)
        end_to_end_latencies.append(latency)
        network_payloads.append(payload)

    execution_strategies = np.array(execution_strategies)
    end_to_end_latencies = np.array(end_to_end_latencies)
    network_payloads = np.array(network_payloads)

    # Print quantitative telemetry summary
    print("=== Distributed Vision Pipeline Telemetry Summary ===")
    print(f"Frames Processed: {total_frames}")
    print(f"Local Edge Execution Strategy Count: {np.sum(execution_strategies == 0)}")
    print(f"Split-Layer Offloading Strategy Count: {np.sum(execution_strategies == 1)}")
    print(f"Full Cloud Migration Strategy Count: {np.sum(execution_strategies == 2)}")
    print(f"Mean End-to-End Latency: {np.mean(end_to_end_latencies):.2f} ms")
    print(f"Mean Network Payload: {np.mean(network_payloads):.2f} Mb/frame")

    # Multi-panel telemetry visualization
    fig, (ax_top, ax_mid, ax_bot) = plt.subplots(3, 1, figsize=(11, 9), sharex=True)

    # 1. Environmental Telemetry
    ax_top.plot(network_bandwidths, label='Available Bandwidth (Mbps)', color='royalblue')
    ax_top.plot(processor_loads, label='Processor Utilization (%)', color='darkorange', linestyle='--')
    ax_top.set_title('Dynamic Environmental Telemetry')
    ax_top.set_ylabel('System Metrics')
    ax_top.legend(loc='upper right')
    ax_top.grid(True)

    # 2. Execution Strategy Timeline
    strategy_colors = ['seagreen' if s == 0 else 'mediumorchid' if s == 1 else 'firebrick' for s in execution_strategies]
    ax_mid.scatter(range(total_frames), execution_strategies, c=strategy_colors, s=65, zorder=3)
    ax_mid.plot(execution_strategies, color='gray', alpha=0.3, zorder=2)
    ax_mid.set_yticks([0, 1, 2])
    ax_mid.set_yticklabels(['Local Edge', 'Split-Layer', 'Cloud Migration'])
    ax_mid.set_ylabel('Active Strategy')
    ax_mid.grid(True)

    # 3. Latency Profile
    ax_bot.plot(end_to_end_latencies, label='Inference Latency (ms)', color='rebeccapurple', linewidth=2)
    ax_bot.set_ylabel('Latency (ms)')
    ax_bot.set_xlabel('Video Frame Index')
    ax_bot.legend(loc='upper right')
    ax_bot.grid(True)

    plt.tight_layout()
    plt.show()

if __name__ == "__main__":
    run_distributed_vision_pipeline()